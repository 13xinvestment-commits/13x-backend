async function upsertCompany(company, data) {
  if (!data) {
    console.log(`  ⚠️  No data for ${company.name}`);
    return false;
  }

  const { error } = await supabase.from('companies').upsert({
    name:          company.name,
    ticker:        company.ticker,
    industry:      company.industry,
    top_trigger:   data.top_trigger,
    all_triggers:  data.all_triggers  || [],
    catalyst_tags: data.catalyst_tags || [],
    score:         data.score         || 0,
    stage:         data.stage         || null,
    quarter:       QUARTER,
    updated_at:    new Date().toISOString(),
  }, { onConflict: 'ticker' });

  if (error) {
    console.error(`  ❌ DB error for ${company.name}: ${error.message}`);
    return false;
  }

  console.log(`  ✅ Saved: ${company.name}`);
  return true;
}

async function runPipeline(limit) {
  // limit: optional — process only first N companies (for testing)
  const list = limit ? COMPANIES.slice(0, limit) : COMPANIES;

  console.log(`\n🚀 BSE Pipeline started — Quarter: ${QUARTER}`);
  console.log(`📋 Processing ${list.length} companies...\n`);

  let success = 0;
  let failed  = 0;
  let noData  = 0;

  for (const company of list) {
    console.log(`⏳ [${list.indexOf(company)+1}/${list.length}] ${company.name}`);

    const transcript = await getTranscript(company);

    if (!transcript) {
      console.log(`  ⚠️  No transcript found — skipping`);
      noData++;
      await sleep(1000);
      continue;
    }

    const data  = await extractTriggers(transcript, company.name);
    const saved = await upsertCompany(company, data);

    if (saved) success++; else failed++;

    await sleep(3000); // 3s pause between companies
  }

  const summary = {
    quarter:     QUARTER,
    success,
    failed,
    noData,
    total:       list.length,
    completedAt: new Date().toISOString(),
  };

  console.log(`\n🎉 Pipeline complete!`);
  console.log(`✅ Saved: ${success} | ❌ Failed: ${failed} | ⚠️ No transcript: ${noData}`);
  return summary;
}

